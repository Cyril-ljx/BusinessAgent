"""
真实性约束 Prompt 模块。

这个模块定义了**所有内容生成相关 prompt 必须 include 的核心约束**。

【使用方法】
在每个内容生成 prompt 中,通过 .format() 嵌入 TRUTHFULNESS_RULES:

    prompt = f'''
    {role_description}

    {TRUTHFULNESS_RULES}

    【任务】
    {task}

    【输入】
    {input_data}
    '''
"""

TRUTHFULNESS_RULES = """
【🔴 真实性原则,严格遵守 — 违反则整份投标书作废】

1. 【参数只来自输入】所有数字、日期、时间、金额、百分比、规格参数
   - 必须从输入文件(招标书 + 知识库)中找到原文出处
   - 找不到的 → 用占位符 [待补充: xxx描述] 标记
   - 严禁基于"常识"或"行业经验"编造任何具体数字

2. 【不允许"优化"参数】
   - 招标要求"≤4 小时"  → 投标书必须写"≤4 小时" 或更严格的"≤3 小时(基于本公司实际能力)"
   - 严禁自作主张写"≤2 小时"试图加分
   - 没有公司实际能力依据时,严格对齐招标要求

3. 【不允许"附加"未提及的内容】
   - 招标要 ISO 27001 → 写 ISO 27001
   - 严禁顺手加 ISO 9001、ISO 14001 等未提及的资质
   - 只有招标书或知识库明确支持时,才能写

4. 【不允许编造历史事实】
   - 业绩案例(项目名、金额、时间、客户)必须来自知识库
   - 人员姓名、职称、资质证书号必须来自知识库
   - 找不到 → 用占位符,严禁虚构

5. 【对方明确要求 vs 推断需求】
   - 招标书直接要求的(如"必须提供 XXX")→ 必须写
   - 业务人员推断"对方可能想要"(如"可能需要补充安全方案")→ 不写,留给业务人员决定
"""
